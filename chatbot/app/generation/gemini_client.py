def generate_answer(
    question: str,
    evidence_context: str,
    fallback_answer: str | None = None,
) -> str:
    """
    Generate a grounded Arabic answer using Gemini.

    If the API key is unavailable or generation fails,
    return the deterministic local answer.
    """

    settings = get_settings()

    if not settings.gemini_api_key:
        logger.info(
            "Gemini API key is not configured. Using local fallback."
        )
        return fallback_answer or (
            "مفتاح Gemini غير متاح حاليًا، "
            "ولا توجد إجابة محلية بديلة."
        )

    if not evidence_context or not evidence_context.strip():
        return (
            "لا توجد بيانات أو أدلة كافية للإجابة عن السؤال حاليًا."
        )

    prompt = f"""
سؤال المستخدم:
{question}

البيانات والأدلة المسترجعة:
{evidence_context}

المطلوب:
1. حدد ما الذي يسأل عنه المستخدم تحديدًا.
2. استخرج فقط البيانات المرتبطة بالسؤال.
3. اربط كل قيمة بالمشروع والفترة والمصدر الصحيح.
4. إذا كانت المعلومة غير متاحة، قل ذلك صراحة.
5. إذا كان السؤال مقارنة، قارن المشروعات بصورة منفصلة ومنظمة.
6. إذا كان السؤال افتراضيًا، حلل السيناريو دون اعتباره واقعة حقيقية.
7. لا تعرض تقريرًا شاملًا إذا كان السؤال يطلب معلومة واحدة.

تعليمات الإخراج:
- اكتب الإجابة النهائية فقط.
- استخدم العربية الواضحة والمباشرة.
- استخدم عناوين Markdown عند الحاجة.
- لا تعرض JSON أو أسماء الحقول البرمجية.
- لا تكرر السؤال أو المقدمات.
- لا تذكر معلومة لا يدعمها السياق.
"""

    try:
        with genai.Client(
            api_key=settings.gemini_api_key
        ) as client:

            response = client.models.generate_content(
                model=settings.gemini_model,
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM_INSTRUCTION,
                    temperature=0.1,
                    max_output_tokens=3000,
                ),
            )

        answer = (response.text or "").strip()

        if answer:
            return answer

        logger.warning("Gemini returned an empty response.")

    except Exception:
        logger.exception("Gemini answer generation failed.")

    return fallback_answer or (
        "تعذر توليد الإجابة حاليًا. يرجى المحاولة مرة أخرى."
    )
